let currentLang = 'en'

// "system" follows Windows' display language, as WebView2 reports it
function setLanguage (pref) {
  if (pref === 'ar' || pref === 'en') currentLang = pref
  else currentLang = (navigator.language || 'en').toLowerCase().startsWith('ar') ? 'ar' : 'en'
  document.documentElement.lang = currentLang
  document.documentElement.dir = currentLang === 'ar' ? 'rtl' : 'ltr'
  return currentLang
}

function t (key, vars) {
  let s = STRINGS[currentLang][key] ?? STRINGS.en[key] ?? key
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] ?? m))
  return s
}
